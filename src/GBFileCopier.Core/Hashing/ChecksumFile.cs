using System.Globalization;
using System.Text;
using GBFileCopier.Core.Resources;

namespace GBFileCopier.Core.Hashing;

/// <summary>A line of a checksum file: a path relative to the file's folder, with '/' separators, and its checksum.</summary>
public sealed record ChecksumEntry(string Path, string Hash);

/// <summary>The contents of a checksum file.</summary>
public sealed record ChecksumList(HashAlgorithmKind Algorithm, IReadOnlyList<ChecksumEntry> Entries);

/// <summary>
/// Checksum files as written by sha256sum, md5sum and similar tools ("hash  path"), the BSD style of
/// shasum --tag and md5 ("SHA256 (path) = hash"), and SFV files for CRC32 ("path HASH").
/// The algorithm comes from the extension (.sha256, .md5, .sfv…) or from the BSD tags.
/// </summary>
public static class ChecksumFile
{
    // BSD tags, as written by shasum --tag, md5, xxhsum --tag
    private static readonly (string Tag, HashAlgorithmKind Kind)[] Tags =
    [
        ("MD5", HashAlgorithmKind.Md5),
        ("SHA1", HashAlgorithmKind.Sha1),
        ("SHA256", HashAlgorithmKind.Sha256),
        ("SHA512", HashAlgorithmKind.Sha512),
        ("CRC32", HashAlgorithmKind.Crc32),
        ("CRC64", HashAlgorithmKind.Crc64),
        ("XXH64", HashAlgorithmKind.XxHash64),
        ("XXH3", HashAlgorithmKind.XxHash3),
        ("XXH128", HashAlgorithmKind.XxHash128),
    ];

    /// <summary>".sha256", ".md5"…; ".sfv" for CRC32, the usual format for it.</summary>
    public static string ExtensionFor(HashAlgorithmKind algorithm) =>
        algorithm switch
        {
            HashAlgorithmKind.None => throw new ArgumentOutOfRangeException(nameof(algorithm), algorithm, "No hash algorithm selected"),
            HashAlgorithmKind.Crc32 => ".sfv",
            _ => "." + HashAlgorithmNames.GetName(algorithm),
        };

    /// <summary>The algorithm of a checksum file, from its extension.</summary>
    public static bool TryGetAlgorithm(string path, out HashAlgorithmKind algorithm)
    {
        var extension = Path.GetExtension(path).TrimStart('.');
        if (extension.Equals("sfv", StringComparison.OrdinalIgnoreCase))
        {
            algorithm = HashAlgorithmKind.Crc32;
            return true;
        }

        return HashAlgorithmNames.TryParse(extension, out algorithm) && algorithm != HashAlgorithmKind.None;
    }

    /// <summary>Hexadecimal digits of a checksum of this algorithm.</summary>
    public static int HexLength(HashAlgorithmKind algorithm) => algorithm switch
    {
        HashAlgorithmKind.Crc32 => 8,
        HashAlgorithmKind.Crc64 or HashAlgorithmKind.XxHash64 or HashAlgorithmKind.XxHash3 => 16,
        HashAlgorithmKind.XxHash128 or HashAlgorithmKind.Md5 => 32,
        HashAlgorithmKind.Sha1 => 40,
        HashAlgorithmKind.Sha256 => 64,
        HashAlgorithmKind.Sha512 => 128,
        _ => 0,
    };

    /// <summary>The checksum file text: one line per entry, '\n' line ends (read fine everywhere).</summary>
    public static string Format(HashAlgorithmKind algorithm, IEnumerable<ChecksumEntry> entries)
    {
        ArgumentNullException.ThrowIfNull(entries);
        var text = new StringBuilder();
        if (algorithm == HashAlgorithmKind.Crc32)
        {
            text.Append(CultureInfo.InvariantCulture, $"; Generated by {AppInfo.Name}\n");
            foreach (var entry in entries)
            {
                text.Append(CultureInfo.InvariantCulture, $"{entry.Path} {entry.Hash.ToUpperInvariant()}\n");
            }

            return text.ToString();
        }

        foreach (var entry in entries)
        {
            // Like sha256sum: a name with a backslash or a line break is escaped, and the line starts with '\'
            var path = entry.Path;
            var escaped = path.Contains('\\', StringComparison.Ordinal) || path.Contains('\n', StringComparison.Ordinal) || path.Contains('\r', StringComparison.Ordinal);
            if (escaped)
            {
                path = path.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\n", "\\n", StringComparison.Ordinal).Replace("\r", "\\r", StringComparison.Ordinal);
            }

            text.Append(CultureInfo.InvariantCulture, $"{(escaped ? "\\" : string.Empty)}{entry.Hash.ToLowerInvariant()}  {path}\n");
        }

        return text.ToString();
    }

    /// <summary>
    /// Reads a checksum file. The algorithm is <paramref name="algorithm"/> if given, otherwise the one
    /// of the BSD tags, of the extension, of a name like SHA256SUMS, or the only one whose checksums
    /// have the length found. UTF-8, or Latin-1 for lists of older Windows tools that are not UTF-8.
    /// </summary>
    /// <exception cref="InvalidDataException">No algorithm, or no valid line.</exception>
    public static ChecksumList Read(string path, HashAlgorithmKind? algorithm = null)
    {
        var bytes = File.ReadAllBytes(path);
        string text;
        try
        {
            text = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true).GetString(bytes);
        }
        catch (DecoderFallbackException)
        {
            text = Encoding.Latin1.GetString(bytes);
        }

        return Parse(text, Path.GetFileName(path), algorithm);
    }

    /// <inheritdoc cref="Read"/>
    /// <param name="text">The contents of the file.</param>
    /// <param name="fileName">Its name, or just its extension.</param>
    /// <param name="algorithm">Overrides what the name and the contents tell.</param>
    public static ChecksumList Parse(string text, string fileName, HashAlgorithmKind? algorithm = null)
    {
        ArgumentNullException.ThrowIfNull(text);
        ArgumentNullException.ThrowIfNull(fileName);
        var extension = Path.GetExtension(fileName);
        var fromName = TryGetAlgorithm(fileName, out var byName) || TryGetSumsAlgorithm(fileName, out byName) ? byName : (HashAlgorithmKind?)null;
        var isSfv = string.Equals(extension, ".sfv", StringComparison.OrdinalIgnoreCase);
        var entries = new List<ChecksumEntry>();
        HashAlgorithmKind? tagged = null;

        foreach (var rawLine in text.TrimStart('﻿').Split('\n'))
        {
            var line = rawLine.TrimEnd('\r');
            // In SFV a line starts with the file name: only ';' starts a comment there
            if (line.Length == 0 || line[0] == ';' || (line[0] == '#' && !isSfv))
            {
                continue;
            }

            if (TryParseBsd(line, out var bsdKind, out var bsdEntry))
            {
                tagged ??= bsdKind;
                if (bsdKind == tagged)
                {
                    entries.Add(bsdEntry);
                }
            }
            else if (isSfv ? TryParseSfv(line, out var entry) : TryParseGnu(line, out entry))
            {
                entries.Add(entry);
            }
        }

        var kind = algorithm ?? tagged ?? fromName ?? ByLength(entries)
            ?? throw new InvalidDataException(Messages.ChecksumFileUnknownAlgorithm);
        var hexLength = HexLength(kind);
        entries.RemoveAll(e => e.Hash.Length != hexLength);
        if (entries.Count == 0)
        {
            throw new InvalidDataException(string.Format(CultureInfo.CurrentCulture, Messages.ChecksumFileEmpty, HashAlgorithmNames.GetName(kind)));
        }

        return new ChecksumList(kind, entries);
    }

    // MD5SUMS, SHA1SUMS, SHA256SUMS, SHA512SUMS: the usual names of lists on Linux and in releases
    private static bool TryGetSumsAlgorithm(string fileName, out HashAlgorithmKind algorithm)
    {
        var name = Path.GetFileNameWithoutExtension(fileName);
        algorithm = HashAlgorithmKind.None;
        return name.EndsWith("SUMS", StringComparison.OrdinalIgnoreCase)
            && HashAlgorithmNames.TryParse(name[..^4], out algorithm) && algorithm != HashAlgorithmKind.None;
    }

    /// <summary>The algorithm when the length of the checksums tells it: 16 or 32 digits fit more than one.</summary>
    private static HashAlgorithmKind? ByLength(List<ChecksumEntry> entries)
    {
        var lengths = entries.Select(e => e.Hash.Length).Distinct().ToList();
        return lengths is [var length] && length is 8 or 40 or 64 or 128
            ? length switch
            {
                8 => HashAlgorithmKind.Crc32,
                40 => HashAlgorithmKind.Sha1,
                64 => HashAlgorithmKind.Sha256,
                _ => HashAlgorithmKind.Sha512,
            }
            : null;
    }

    // "SHA256 (dir/name) = 0123…"
    private static bool TryParseBsd(string line, out HashAlgorithmKind kind, out ChecksumEntry entry)
    {
        kind = HashAlgorithmKind.None;
        entry = null!;
        var open = line.IndexOf(" (", StringComparison.Ordinal);
        var close = line.LastIndexOf(") = ", StringComparison.Ordinal);
        if (open <= 0 || close < open)
        {
            return false;
        }

        var tag = line[..open];
        var match = Array.FindIndex(Tags, t => t.Tag.Equals(tag, StringComparison.OrdinalIgnoreCase));
        var hash = line[(close + 4)..].Trim();
        if (match < 0 || !IsHex(hash))
        {
            return false;
        }

        kind = Tags[match].Kind;
        entry = new ChecksumEntry(line[(open + 2)..close], hash.ToLowerInvariant());
        return true;
    }

    // "0123…  dir/name" (text mode), "0123… *dir/name" (binary mode), "0123… dir/name" (md5 -r);
    // "\0123…  a\\b" for an escaped name
    private static bool TryParseGnu(string line, out ChecksumEntry entry)
    {
        entry = null!;
        var escaped = line.StartsWith('\\');
        var start = escaped ? 1 : 0;
        var space = line.IndexOf(' ', start);
        if (space <= start || space + 1 >= line.Length)
        {
            return false;
        }

        // xxhsum writes XXH3 checksums as "XXH3_0123…"
        var hash = line[start..space];
        if (hash.StartsWith("XXH3_", StringComparison.Ordinal))
        {
            hash = hash[5..];
        }

        var path = line[(space + (line[space + 1] is ' ' or '*' ? 2 : 1))..];
        if (!IsHex(hash) || path.Length == 0)
        {
            return false;
        }

        if (escaped)
        {
            path = Unescape(path);
        }

        entry = new ChecksumEntry(path, hash.ToLowerInvariant());
        return true;
    }

    // "dir/name 0123ABCD": the name can contain spaces, the checksum is after the last one
    private static bool TryParseSfv(string line, out ChecksumEntry entry)
    {
        entry = null!;
        var trimmed = line.TrimEnd();
        var space = trimmed.LastIndexOf(' ');
        if (space <= 0)
        {
            return false;
        }

        var hash = trimmed[(space + 1)..];
        if (!IsHex(hash))
        {
            return false;
        }

        entry = new ChecksumEntry(trimmed[..space].TrimEnd(), hash.ToLowerInvariant());
        return true;
    }

    private static string Unescape(string path)
    {
        var text = new StringBuilder(path.Length);
        for (var i = 0; i < path.Length; i++)
        {
            if (path[i] == '\\' && i + 1 < path.Length)
            {
                i++;
                text.Append(path[i] switch
                {
                    'n' => '\n',
                    'r' => '\r',
                    _ => path[i],
                });
            }
            else
            {
                text.Append(path[i]);
            }
        }

        return text.ToString();
    }

    private static bool IsHex(string text) => text.Length > 0 && text.All(char.IsAsciiHexDigit);
}
